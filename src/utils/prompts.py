def get_fusion_prompt(responses: Dict[str, str], question: str) -> str:
    """生成多专家回答融合的提示词"""
    experts_text = ""
    for name, answer in responses.items():
        expert_display = {
            "craft_expert": "🎨 技艺知识专家",
            "history_expert": "📜 历史文化专家",
            "heritage_expert": "🏛️ 传承现状专家",
        }.get(name, name)
        experts_text += f"\n### {expert_display}\n{answer}\n"

    return f"""你是一个非遗知识融合专家。请将以下多个专家的回答融合为一个完整、连贯的最终回答。

## 用户原始问题
{question}

## 各专家回答
{experts_text}

## 融合要求
1. 去除各专家回答中的重复信息和矛盾之处
2. 按照逻辑顺序组织内容（先概述，再工艺/历史，最后传承现状）
3. 保持每个专家的核心观点和特色
4. 注明信息来源（标注来自哪位专家）
5. 语言流畅自然，避免生硬拼接
6. 如果专家之间的信息有补充关系，请自然地串联起来
7. 控制总长度，不要过于冗长

请生成融合后的最终回答："""


